use anyhow::{Context, Result, bail};
use sqlx::{PgPool, postgres::PgPoolOptions};
use std::time::Duration;

// Retain the deployed migration ledger and SQL to preserve existing databases.
// The Goose-compatible format is parsed here without a Go runtime or dependency.
const MIGRATIONS: &[(i64, &str)] = &[
    (1, include_str!("../migrations/001_init.sql")),
    (
        2,
        include_str!("../migrations/002_global_portfolio_slug.sql"),
    ),
    (3, include_str!("../migrations/003_portfolio_gap.sql")),
    (4, include_str!("../migrations/004_portfolio_matte.sql")),
    (5, include_str!("../migrations/005_row_break.sql")),
    (6, include_str!("../migrations/006_admin.sql")),
    (7, include_str!("../migrations/007_default_no_perms.sql")),
    (8, include_str!("../migrations/008_canvas.sql")),
    (9, include_str!("../migrations/009_library_folders.sql")),
];

pub async fn connect(url: &str) -> Result<PgPool> {
    PgPoolOptions::new()
        .max_connections(10)
        .acquire_timeout(Duration::from_secs(10))
        .connect(url)
        .await
        .context("connecting to PostgreSQL")
}

fn up_sql(source: &str) -> Result<&str> {
    let (_, source) = source
        .split_once("-- +goose Up")
        .context("missing Goose Up marker")?;
    let (up, _) = source
        .split_once("-- +goose Down")
        .context("missing Goose Down marker")?;
    Ok(up.trim())
}

pub async fn migrate(pool: &PgPool) -> Result<()> {
    let mut tx = pool.begin().await?;
    // Serialize migration startup across application instances.
    sqlx::query("SELECT pg_advisory_xact_lock(719482163)")
        .execute(&mut *tx)
        .await?;
    sqlx::raw_sql(
        "CREATE TABLE IF NOT EXISTS goose_db_version (
        id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        version_id bigint NOT NULL,
        is_applied boolean NOT NULL,
        tstamp timestamp NOT NULL DEFAULT now()
    )",
    )
    .execute(&mut *tx)
    .await?;
    let history: Vec<(i64, bool)> = sqlx::query_as(
        "SELECT DISTINCT ON (version_id) version_id, is_applied
         FROM goose_db_version ORDER BY version_id, id DESC",
    )
    .fetch_all(&mut *tx)
    .await?;
    if history
        .iter()
        .any(|(version, applied)| *applied && *version > MIGRATIONS.last().unwrap().0)
    {
        bail!("database schema is newer than this backend; refusing to start");
    }
    if history.is_empty() {
        sqlx::query("INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)")
            .execute(&mut *tx)
            .await?;
    }
    for &(version, source) in MIGRATIONS {
        if history.contains(&(version, true)) {
            continue;
        }
        tracing::info!(version, "applying database migration");
        sqlx::raw_sql(up_sql(source)?)
            .execute(&mut *tx)
            .await
            .with_context(|| format!("applying migration {version}"))?;
        sqlx::query("INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, true)")
            .bind(version)
            .execute(&mut *tx)
            .await?;
    }
    tx.commit().await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_migrations_only_execute_the_up_section() {
        for &(_, source) in MIGRATIONS {
            let up = up_sql(source).unwrap();
            assert!(!up.is_empty());
            assert!(!up.contains("-- +goose Down"));
        }
        assert!(!up_sql(MIGRATIONS[0].1).unwrap().contains("DROP TABLE"));
    }

    #[test]
    fn rejects_sql_without_explicit_migration_boundaries() {
        assert!(up_sql("DROP TABLE users").is_err());
        assert!(up_sql("-- +goose Up\nSELECT 1").is_err());
    }
}
